#!/usr/bin/env python3
"""Build derived files for the archived, leakage-safe five-fold run split.

The input is the Label Studio JSON export used by the project.  Every task is
treated as one CTI report. The test allocation is read from the exact
``fold_manifest_v4.json`` archived with the V10 run; it is not regenerated by
a second fold-assignment algorithm that happens to use the same seed.

For outer fold k, fold k is the test partition. The saved seed-42 training and
validation identifiers are read from ``run_partitions_seed_42.json``.

This rotating 3/1/1 protocol ensures that each report is used as test data
exactly once and that no report contributes content to more than one partition
within a run.
"""

from __future__ import annotations

import argparse
import csv
import json
import re
import tempfile
from collections import Counter
from pathlib import Path
from typing import Any


UUID_PREFIX = re.compile(r"^[0-9a-fA-F]{8}-")
SPLIT_SEED = 11800
CORE_ENTITY_TYPES = (
    "attack-pattern",
    "campaign",
    "domain-name",
    "identity",
    "indicator",
    "intrusion-set",
    "location",
    "malware",
    "tool",
    "vulnerability",
)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--annotations",
        type=Path,
        default=Path("data/Annotations.json"),
        help="Label Studio JSON export (one task per CTI report).",
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("experiments/cv_manifest"),
    )
    parser.add_argument("--folds", type=int, default=5)
    parser.add_argument("--seed", type=int, default=SPLIT_SEED)
    parser.add_argument(
        "--run-manifest",
        type=Path,
        default=Path("experiments/cv_manifest/fold_manifest_v4.json"),
        help="Exact numeric document-index manifest archived with the V10 run.",
    )
    parser.add_argument(
        "--run-partitions",
        type=Path,
        default=Path("experiments/cv_manifest/run_partitions_seed_42.json"),
        help="Saved seed-42 train/validation/test partitions and evaluation counts.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that a fresh manifest matches the checked-in output files.",
    )
    return parser.parse_args()


def source_name(task: dict[str, Any]) -> str:
    uploaded = str(task.get("file_upload") or "").strip()
    if uploaded:
        return UUID_PREFIX.sub("", uploaded)
    return f"task-{task['id']}"


def extract_document(task: dict[str, Any]) -> dict[str, Any]:
    annotations = task.get("annotations") or []
    if not annotations:
        raise ValueError(f"Task {task.get('id')} has no completed annotation")

    results = annotations[0].get("result") or []
    entity_counts: Counter[str] = Counter()
    relation_counts: Counter[str] = Counter()

    for item in results:
        item_type = item.get("type")
        if item_type == "labels":
            labels = item.get("value", {}).get("labels") or []
            if labels:
                entity_counts[str(labels[0])] += 1
        elif item_type == "relation":
            labels = item.get("labels") or []
            relation_counts[str(labels[0]) if labels else "<untyped>"] += 1

    text = str(task.get("data", {}).get("text") or "")
    return {
        "document_id": str(task["id"]),
        "source_file": source_name(task),
        "characters": len(text),
        "entity_mentions": sum(entity_counts.values()),
        "relation_instances": sum(relation_counts.values()),
        "entity_counts": dict(sorted(entity_counts.items())),
        "relation_counts": dict(sorted(relation_counts.items())),
    }


def load_archived_run_allocation(
    documents: list[dict[str, Any]],
    run_manifest_path: Path,
    run_partitions_path: Path,
    n_folds: int,
    split_seed: int,
) -> tuple[list[list[dict[str, Any]]], dict[str, Any]]:
    """Map the archived run's numeric indices to stable annotation task IDs."""
    run_manifest = json.loads(run_manifest_path.read_text(encoding="utf-8"))
    partitions = json.loads(run_partitions_path.read_text(encoding="utf-8"))
    if int(run_manifest.get("split_seed", -1)) != split_seed:
        raise ValueError("Archived run manifest split seed does not match --seed")
    if int(partitions.get("split_seed", -1)) != split_seed:
        raise ValueError("Archived run partitions split seed does not match --seed")

    numeric_folds = run_manifest.get("folds")
    if not isinstance(numeric_folds, list) or len(numeric_folds) != n_folds:
        raise ValueError("Archived run manifest has the wrong number of folds")
    flattened = [int(index) for fold in numeric_folds for index in fold]
    expected_indices = list(range(len(documents)))
    if sorted(flattened) != expected_indices or len(flattened) != len(set(flattened)):
        raise ValueError("Archived run manifest must cover each annotation index once")

    folds = [[documents[int(index)] for index in fold] for fold in numeric_folds]
    saved_folds = partitions.get("outer_folds") or []
    if len(saved_folds) != n_folds:
        raise ValueError("Saved run partitions have the wrong number of folds")

    document_ids_by_index = [document["document_id"] for document in documents]
    all_ids = set(document_ids_by_index)
    for fold_index, saved in enumerate(saved_folds):
        expected_test_indices = [int(index) for index in numeric_folds[fold_index]]
        if saved.get("test_document_indices") != expected_test_indices:
            raise ValueError(f"Fold {fold_index + 1} test indices differ from run manifest")
        for partition_name in ("train", "validation", "test"):
            indices = [
                int(index)
                for index in saved.get(f"{partition_name}_document_indices", [])
            ]
            stable_ids = [document_ids_by_index[index] for index in indices]
            if stable_ids != saved.get(f"{partition_name}_document_ids"):
                raise ValueError(
                    f"Fold {fold_index + 1} {partition_name} ID mapping is stale"
                )
        train = set(saved["train_document_ids"])
        validation = set(saved["validation_document_ids"])
        test = set(saved["test_document_ids"])
        if train & validation or train & test or validation & test:
            raise ValueError(f"Fold {fold_index + 1} partitions overlap")
        if train | validation | test != all_ids:
            raise ValueError(f"Fold {fold_index + 1} partitions are incomplete")
        raw_relations = sum(
            document["relation_instances"] for document in folds[fold_index]
        )
        if raw_relations != int(saved["raw_relation_instances"]):
            raise ValueError(f"Fold {fold_index + 1} raw relation count is stale")

    return folds, partitions


def write_outputs(
    documents: list[dict[str, Any]],
    folds: list[list[dict[str, Any]]],
    partitions: dict[str, Any],
    output_dir: Path,
    seed: int,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    assignment = {
        document["document_id"]: fold_index
        for fold_index, fold in enumerate(folds, start=1)
        for document in fold
    }
    if set(assignment) != {document["document_id"] for document in documents}:
        raise RuntimeError("Fold assignment is incomplete")

    manifest = {
        "protocol": "five-fold document-level cross-validation with saved within-run validation partitions",
        "split_seed": seed,
        "run_seed": int(partitions["run_seed"]),
        "dataset_sha256": partitions["dataset_sha256"],
        "source_run_manifest": "fold_manifest_v4.json",
        "source_run_partitions": "run_partitions_seed_42.json",
        "core_entity_types": list(CORE_ENTITY_TYPES),
        "number_of_folds": len(folds),
        "number_of_documents": len(documents),
        "folds": [
            {
                "fold": fold_index,
                "documents": [document["document_id"] for document in fold],
                "source_files": [document["source_file"] for document in fold],
            }
            for fold_index, fold in enumerate(folds, start=1)
        ],
        "documents": [dict(document, fold=assignment[document["document_id"]]) for document in documents],
    }
    (output_dir / "document_folds.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )

    with (output_dir / "document_folds.csv").open("w", newline="", encoding="utf-8") as stream:
        fieldnames = [
            "document_id",
            "source_file",
            "fold",
            "characters",
            "entity_mentions",
            "relation_instances",
        ]
        writer = csv.DictWriter(stream, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        for document in sorted(documents, key=lambda item: int(item["document_id"])):
            row = {key: document[key] for key in fieldnames if key != "fold"}
            row["fold"] = assignment[document["document_id"]]
            writer.writerow(row)

    split_dir = output_dir / "outer_splits"
    split_dir.mkdir(exist_ok=True)
    for zero_based_fold, saved in enumerate(partitions["outer_folds"]):
        split = {
            "outer_fold_index": zero_based_fold,
            "run_fold": int(saved["fold"]),
            "split_seed": seed,
            "run_seed": int(partitions["run_seed"]),
            "dataset_sha256": partitions["dataset_sha256"],
            "train_document_ids": saved["train_document_ids"],
            "validation_document_ids": saved["validation_document_ids"],
            "test_document_ids": saved["test_document_ids"],
        }
        (split_dir / f"outer_fold_{zero_based_fold}.json").write_text(
            json.dumps(split, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
        )

    with (output_dir / "fold_summary.csv").open("w", newline="", encoding="utf-8") as stream:
        fieldnames = [
            "fold",
            "documents",
            "entity_mentions",
            "relation_instances",
            "evaluation_entity_instances",
            "evaluation_relation_instances",
            "characters",
        ]
        writer = csv.DictWriter(stream, fieldnames=fieldnames, lineterminator="\n")
        writer.writeheader()
        for fold_index, fold in enumerate(folds, start=1):
            saved = partitions["outer_folds"][fold_index - 1]
            writer.writerow(
                {
                    "fold": fold_index,
                    "documents": len(fold),
                    "entity_mentions": sum(d["entity_mentions"] for d in fold),
                    "relation_instances": sum(d["relation_instances"] for d in fold),
                    "evaluation_entity_instances": saved[
                        "evaluation_entity_instances"
                    ],
                    "evaluation_relation_instances": saved[
                        "evaluation_relation_instances"
                    ],
                    "characters": sum(d["characters"] for d in fold),
                }
            )


def main() -> None:
    args = parse_args()
    tasks = json.loads(args.annotations.read_text(encoding="utf-8-sig"))
    documents = [extract_document(task) for task in tasks]
    ids = [document["document_id"] for document in documents]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate document/task identifiers detected")
    folds, partitions = load_archived_run_allocation(
        documents,
        args.run_manifest,
        args.run_partitions,
        args.folds,
        args.seed,
    )
    if args.check:
        with tempfile.TemporaryDirectory(prefix="document-cv-check-") as temp_dir:
            generated_dir = Path(temp_dir)
            write_outputs(documents, folds, partitions, generated_dir, args.seed)
            generated_files = {
                path.relative_to(generated_dir): path
                for path in generated_dir.rglob("*")
                if path.is_file()
            }
            checked_in_files = {
                relative_path: args.output_dir / relative_path
                for relative_path in generated_files
                if (args.output_dir / relative_path).is_file()
            }
            if set(generated_files) != set(checked_in_files):
                raise SystemExit(
                    "Manifest file set differs: "
                    f"generated={sorted(map(str, generated_files))}, "
                    f"checked_in={sorted(map(str, checked_in_files))}"
                )
            mismatches = []
            for relative_path, generated_path in generated_files.items():
                generated = generated_path.read_text(encoding="utf-8").replace("\r\n", "\n")
                checked_in = checked_in_files[relative_path].read_text(
                    encoding="utf-8"
                ).replace("\r\n", "\n")
                if generated != checked_in:
                    mismatches.append(str(relative_path))
            if mismatches:
                raise SystemExit(f"Checked-in manifest differs: {mismatches}")
        print(
            "Fresh generation matches archived run manifest and checked-in "
            "derived files"
        )
        return

    write_outputs(documents, folds, partitions, args.output_dir, args.seed)
    print(f"Wrote {args.folds} document folds for {len(documents)} reports to {args.output_dir}")


if __name__ == "__main__":
    main()
